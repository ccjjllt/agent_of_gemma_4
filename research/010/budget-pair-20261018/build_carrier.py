"""Package the bounded P010 CT Agent budget experiment; does not run or submit it."""
import ast
import base64
import hashlib
import io
import json
from pathlib import Path
import zipfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
PREFIX = HERE.relative_to(ROOT)
IMAGE = 'gcr.io/kaggle-private-byod/python@sha256:37c64f7dd9c54116ecd1bcc88817c5469b88387388fade02bfa8bf3fc647d461'
paths = [
    PREFIX / name for name in ('coordinator.py', 'attempt_worker.py', 'supervisor.py',
                              'tasks-selected.jsonl', 'experiment-manifest.json')]
missing = [str(p) for p in paths if not (ROOT / p).is_file()]
if missing:
    raise SystemExit('Required experiment artifact not ready: ' + ', '.join(missing))
manifest = {'image_pin': IMAGE, 'official_wheelhouse_version': 31,
            'task_ids': ['rich_3067', 'fastapi_14463', 'requests_7205'],
            'platform_wall_seconds': 1800, 'worker_wall_seconds': 1680,
            'evaluation_deadline_seconds': 1620, 'archive_deadline_seconds': 1740,
            'adapter_kernel_version': 1,
            'adapter_sha256': 'c7845c23852dbc701a267eaa58be87464af90e25c62bfffb0286ac1033945ba2',
            'training_in_this_run': False,
            'max_concurrent_attempts': 4,
            'files': {str(p): {'bytes': (ROOT / p).stat().st_size,
                             'sha256': hashlib.sha256((ROOT / p).read_bytes()).hexdigest()} for p in paths}}
manifest_text = json.dumps(manifest, indent=2) + '\n'
(HERE / 'carrier-manifest.json').write_text(manifest_text)
buf = io.BytesIO()
with zipfile.ZipFile(buf, 'w', zipfile.ZIP_DEFLATED) as archive:
    for path in paths:
        payload = (ROOT / path).read_bytes()
        if path.suffix == '.py':
            ast.parse(payload, filename=str(path))
        archive.writestr(str(path), payload)
    archive.writestr(str(PREFIX / 'carrier-manifest.json'), manifest_text)
archive_bytes = buf.getvalue()
bootstrap = '''# Generated by build_carrier.py. Execution starts the bounded GPU experiment.
import base64, hashlib, io, os, runpy, time, uuid, zipfile
from pathlib import Path
PAYLOAD = {payload!r}
EXPECTED_SHA256 = {digest!r}
raw = base64.b64decode(PAYLOAD)
assert hashlib.sha256(raw).hexdigest() == EXPECTED_SHA256
bundle = Path('/kaggle/working') / ('p010-bundle-' + uuid.uuid4().hex[:8])
bundle.mkdir()
with zipfile.ZipFile(io.BytesIO(raw)) as archive:
    for member in archive.infolist():
        target = (bundle / member.filename).resolve()
        assert target.is_relative_to(bundle.resolve()), 'Invalid archive member'
    archive.extractall(bundle)
os.environ['P010_BUNDLE_ROOT'] = str(bundle)
runpy.run_path(str(bundle / {supervisor!r}), run_name='__main__')
'''.format(payload=base64.b64encode(archive_bytes).decode(),digest=hashlib.sha256(archive_bytes).hexdigest(),supervisor=str(PREFIX / 'supervisor.py'))
ast.parse(bootstrap)
kernel = HERE / 'kernel'
kernel.mkdir(exist_ok=True)
(kernel / 'experiment.py').write_text(bootstrap)
metadata = {'id': 'ccjjllt/p010-12b-budget-agent-pair', 'title': 'P010 12B Budget Agent Pair',
            'code_file': 'experiment.py', 'language': 'python', 'kernel_type': 'script',
            'is_private': True, 'enable_gpu': True, 'enable_tpu': False, 'enable_internet': False,
            'dataset_sources': ['metric/gemma-4-developer-agent-wheelhouse'],
            'competition_sources': ['gemma-4-developer-agent'],
            'kernel_sources': ['ccjjllt/p009-12b-sft-agent-pair'],
            'model_sources': ['google/gemma-4/Other/gemma-4-12b-it-qat-w4a16-ct/2'],
            'docker_image': IMAGE, 'docker_image_pinning_type': 'original'}
(kernel / 'kernel-metadata.json').write_text(json.dumps(metadata, indent=2) + '\n')
print(json.dumps({'source_files': len(paths), 'compressed_bundle_bytes': len(archive_bytes),
                  'carrier': str(kernel / 'experiment.py'), 'kernel': metadata['id']}))
